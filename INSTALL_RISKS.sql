USE qmsportaldb;
CREATE TABLE IF NOT EXISTS RiskIssues (
 Id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY, Kind VARCHAR(10) NOT NULL, Title VARCHAR(200) NOT NULL,
 Category VARCHAR(50) NOT NULL, Description TEXT NOT NULL, ActionPlan TEXT NOT NULL,
 Probability INT NOT NULL, Impact INT NOT NULL, Status VARCHAR(20) NOT NULL, TeamId BIGINT NOT NULL,
 OwnerId BIGINT NOT NULL, CreatedById BIGINT NOT NULL, DeliverableId BIGINT NULL, DueDate DATE NOT NULL,
 UpdatedUtc DATETIME(6) NOT NULL, Version CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
 INDEX IX_RiskIssues_TeamId (TeamId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS RiskIssueAudits (
 Id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY, RiskIssueId BIGINT NOT NULL, Actor VARCHAR(100) NOT NULL,
 AtUtc DATETIME(6) NOT NULL, BeforeJson LONGTEXT NOT NULL, AfterJson LONGTEXT NOT NULL,
 INDEX IX_RiskIssueAudits_RiskIssueId (RiskIssueId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
